let currentLang = localStorage.getItem('puck_lang') || 'en';

function setLanguage(langCode) {
    currentLang = langCode;
    localStorage.setItem('puck_lang', currentLang);
    applyTranslations();
}

function getTranslation(key) {
    if (TRANSLATIONS[currentLang] && TRANSLATIONS[currentLang][key]) return TRANSLATIONS[currentLang][key];
    if (TRANSLATIONS['en'] && TRANSLATIONS['en'][key]) return TRANSLATIONS['en'][key];
    return key; 
}

function applyTranslations() {
    document.querySelectorAll('[data-i18n]').forEach(el => {
        let key = el.getAttribute('data-i18n');
        let text = getTranslation(key);
        if (el.tagName === 'INPUT' && el.hasAttribute('placeholder')) {
            el.setAttribute('placeholder', text);
        } else {
            el.innerHTML = text;
        }
    });
}

document.addEventListener('DOMContentLoaded', applyTranslations);